const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const { nativeTarget, prepareNative } = require('./native-package.cjs');
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--target')) throw new Error('Usage: npm run package -- --target PLATFORM-ARCH');
const target = nativeTarget(args[1]);
const { ignoreFile } = prepareNative(root, target);
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const artifactDirectory = process.env.PATCHPORT_ARTIFACT_DIR || path.resolve(root, '../../.bridge/artifacts');
const output = path.resolve(artifactDirectory, `patchport-${manifest.version}-${target}.vsix`);
fs.mkdirSync(path.dirname(output), { recursive: true });
const vsceManifest = require.resolve('@vscode/vsce/package.json');
const bin = path.resolve(path.dirname(vsceManifest), JSON.parse(fs.readFileSync(vsceManifest, 'utf8')).bin.vsce);
const result = spawnSync(process.execPath, [bin, 'package', '--out', output, '--target', target, '--ignoreFile', ignoreFile, '--no-rewrite-relative-links'], { cwd: root, stdio: 'inherit', windowsHide: true });
if (result.error) throw result.error;
process.exitCode = result.status ?? 1;
